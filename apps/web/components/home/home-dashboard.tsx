function AgentsSection({ agents, feed, loading, signedIn }: { agents: AgentDoc[]; feed: FeedItem[]; loading: boolean; signedIn: boolean }) {
  const rows = useMemo(() => {
    return agents
      .map((a) => {
        const own = feed.filter((v) => v.mint === a.mintAddress).sort((x, y) => y.createdAt - x.createdAt);
        return {
          agent: a,
          lastPost: own[0] ?? null,
          lastPosted: own.find((v) => v.state === "posted") ?? null,
          videoCount: own.length,
        };
      })
      .sort((a, b) => (b.lastPost?.createdAt ?? 0) - (a.lastPost?.createdAt ?? 0))
      .slice(0, 6);
  }, [agents, feed]);

  return (
    <div className="flex min-w-0 flex-col">
      <div className="flex items-center justify-between border-b border-white/10 pb-3">
        <span className="text-[19px] font-semibold text-white">My Influencers {signedIn ? `(${rows.length})` : ""}</span>
      </div>

      {!signedIn && (
        <div className="mt-10 flex flex-1 flex-col items-center justify-center gap-3 rounded-xl border border-white/10 bg-white/[0.02] py-16 text-center">
          <UserPlus className="size-7 text-white/25" />
          <p className="text-[13.5px] font-medium text-white/70">Sign in to see your agents</p>
        </div>
      )}

      {signedIn && loading && (
        <div className="mt-4 flex flex-col gap-2.5">
          {Array.from({ length: 4 }, (_, i) => (
            <div key={i} className="h-[120px] animate-pulse rounded-xl border border-white/10 bg-white/[0.03]" />
          ))}
        </div>
      )}

      {signedIn && !loading && rows.length === 0 && (
        <div className="mt-10 flex flex-1 flex-col items-center justify-center gap-3 rounded-xl border border-white/10 bg-white/[0.02] py-16 text-center">
          <UserPlus className="size-7 text-white/25" />
          <p className="text-[13.5px] font-medium text-white/70">No agents yet</p>
          <div className="flex items-center gap-3 text-[12px] font-medium">
            <Link href="/builder?type=clipping" className="text-white/60 underline decoration-white/20 underline-offset-4 hover:text-white/90">
              Launch an AI Clipper
            </Link>
            <span className="text-white/20">·</span>
            <Link href="/studio/build" className="text-white/60 underline decoration-white/20 underline-offset-4 hover:text-white/90">
              Launch an AI Influencer
            </Link>
          </div>
        </div>
      )}

      {signedIn && !loading && rows.length > 0 && (
        <div className="mt-4 flex flex-col gap-2.5">
          {rows.map(({ agent, lastPost, lastPosted, videoCount }) => (
            <AgentCard key={agent.mintAddress} agent={agent} lastPost={lastPost} lastPosted={lastPosted} videoCount={videoCount} />
          ))}
          {agents.length > rows.length && (
            <Link
              href="/studio"
              className="mt-1 flex items-center justify-center gap-1.5 rounded-xl border border-white/10 bg-white/[0.02] py-2.5 text-[12.5px] font-medium text-white/60 transition-colors hover:bg-white/[0.06] hover:text-white"
            >
              Show all {agents.length} agents <ArrowRight className="size-3.5" />
            </Link>
          )}
        </div>
      )}
    </div>
  );
}

const CLIPS_PAGE = 8;

// ── Shared data fetch for both panels — one subscription, not two ──────────
function DashboardLists() {
  const { profile } = useSupabaseAuth();
  const signedIn = !!profile;
  const myWallets = useMemo(() => (profile?.walletAddresses ?? []).filter(Boolean), [profile?.walletAddresses]);

  const myAgents = useQuery(
    api.influencers.listByCreators,
    signedIn && myWallets.length ? { creatorWallets: myWallets } : "skip",
  ) as AgentDoc[] | undefined;

  // Brand-new accounts (however they registered: email, Google or wallet) start
  // at agent setup, not on an empty dashboard. Once per browser session so a
  // user who backs out isn't bounced repeatedly.
  const router = useRouter();
  useEffect(() => {
    if (!signedIn || myAgents === undefined || myAgents.length > 0) return;
    try {
      if (window.sessionStorage.getItem("vello:onboard-redirected")) return;
      window.sessionStorage.setItem("vello:onboard-redirected", "1");
    } catch { /* private mode: redirect anyway */ }
    router.replace("/builder");
  }, [signedIn, myAgents, router]);

  const feedResult = useQuery(api.clipJobs.globalVideoFeed, signedIn ? { limit: 200 } : "skip") as
    | { items: FeedItem[] }
    | undefined;
  const feed = feedResult?.items;

  const myVideos = useMemo(() => {
    if (!signedIn || !myAgents || !feed) return [];
    const mints = new Set(myAgents.map((a) => a.mintAddress));
    return feed.filter((v) => mints.has(v.mint)).sort((a, b) => b.createdAt - a.createdAt);
  }, [signedIn, myAgents, feed]);

  const loading = signedIn && (myAgents === undefined || feed === undefined);
  const [visibleCount, setVisibleCount] = useState(CLIPS_PAGE);
  const recentVideos = useMemo(() => myVideos.slice(0, visibleCount), [myVideos, visibleCount]);
  const reduceMotion = useReducedMotion();
  const [openItem, setOpenItem] = useState<FeedItem | null>(null);

  return (
    <div className="mt-16 grid w-full grid-cols-1 gap-8 px-6 pb-16 sm:px-10 lg:grid-cols-[1fr_360px]">
      <AnimatePresence>
        {openItem && <VideoModal key={openItem.id} item={openItem} onClose={() => setOpenItem(null)} />}
      </AnimatePresence>
      <div className="min-w-0">
        <div className="flex items-center justify-between border-b border-white/10 pb-3">
          <span className="text-[19px] font-semibold text-white">Recent Clips {signedIn ? `(${myVideos.length})` : ""}</span>
        </div>

        {!signedIn && (
          <div className="mt-10 flex flex-col items-center justify-center gap-3 rounded-xl border border-white/10 bg-white/[0.02] py-16 text-center">
            <FolderOpen className="size-7 text-white/25" />
            <p className="text-[13.5px] font-medium text-white/70">Sign in to see everything your agents have made</p>
            <p className="max-w-sm text-[12px] text-white/40">
              Every clip and generated video your agents post shows up here, titled and searchable, the moment you&apos;re signed in.
            </p>
          </div>
        )}

        {signedIn && loading && (
          <div className="mt-6 grid grid-cols-2 gap-x-6 gap-y-9 sm:grid-cols-3 xl:grid-cols-4">
            {Array.from({ length: 8 }, (_, i) => (
              <div key={i} className="aspect-video animate-pulse rounded-xl border border-white/10 bg-white/[0.03]" />
            ))}
          </div>
        )}

        {signedIn && !loading && myVideos.length === 0 && (
          <div className="mt-10 flex flex-col items-center justify-center gap-3 rounded-xl border border-white/10 bg-white/[0.02] py-16 text-center">
            <FolderOpen className="size-7 text-white/25" />
            <p className="text-[13.5px] font-medium text-white/70">No generations yet</p>
            <p className="max-w-sm text-[12px] text-white/40">
              Drop a video above or launch an agent — everything it clips or generates will show up here with its title.
            </p>
          </div>
        )}

        {signedIn && !loading && recentVideos.length > 0 && (
          <>
            <div className="mt-6 grid grid-cols-2 gap-x-6 gap-y-9 sm:grid-cols-3 xl:grid-cols-4">
              {recentVideos.map((v, i) => (
                // Each newly revealed batch staggers in by its index within
                // the batch, so "Show more" cascades instead of popping in.
                <motion.div
                  key={v.id}
                  initial={reduceMotion ? false : { opacity: 0, y: 24, filter: "blur(6px)" }}
                  animate={{ opacity: 1, y: 0, filter: "blur(0px)" }}
                  transition={{ type: "spring", stiffness: 260, damping: 28, delay: (i % CLIPS_PAGE) * 0.05 }}
                >
                  <ProjectCard item={v} onOpen={setOpenItem} />
                </motion.div>
              ))}
            </div>
            {myVideos.length > recentVideos.length && (
              <div className="mt-10 flex justify-center">
                <button
                  type="button"
                  onClick={() => setVisibleCount((n) => n + CLIPS_PAGE)}
                  className="group flex items-center gap-2 rounded-full border border-white/10 bg-white/[0.03] px-5 py-2.5 text-[13px] font-medium text-white/70 transition-all hover:border-white/20 hover:bg-white/[0.07] hover:text-white active:scale-[0.97]"
                >
                  Show more
                  <span className="text-white/35">{myVideos.length - recentVideos.length} left</span>
                  <ChevronDown className="size-3.5 transition-transform group-hover:translate-y-0.5" />
                </button>
              </div>
            )}
          </>
        )}
      </div>

      <AgentsSection agents={myAgents ?? []} feed={feed ?? []} loading={!!loading} signedIn={signedIn} />
    </div>
  );
}


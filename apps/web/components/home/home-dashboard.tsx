function FlipCharacter({ value, index }: { value: string; index: number }) {
  const reduceMotion = useReducedMotion();
  const isDigit = /\d/.test(value);

  if (!isDigit) {
    return <span className="w-1.5 text-center text-[13px] font-semibold text-white/35 sm:w-2 sm:text-[15px]">{value}</span>;
  }

  return (
    <span
      className="relative h-8 w-[23px] overflow-hidden rounded-[4px] border border-white/12 bg-black/55 shadow-[inset_0_1px_0_rgba(255,255,255,0.09),0_5px_14px_rgba(0,0,0,0.28)] sm:h-9 sm:w-[27px]"
      style={{ perspective: 180 }}
    >
      <span aria-hidden className="absolute inset-x-0 top-1/2 z-10 h-px bg-black/70" />
      <span aria-hidden className="absolute inset-x-0 top-0 h-1/2 bg-white/[0.035]" />
      <AnimatePresence initial={false} mode="popLayout">
        <motion.span
          key={`${index}-${value}`}
          initial={reduceMotion ? { opacity: 0 } : { y: "-72%", rotateX: -82, opacity: 0, filter: "blur(3px)" }}
          animate={{ y: "0%", rotateX: 0, opacity: 1, filter: "blur(0px)" }}
          exit={reduceMotion ? { opacity: 0 } : { y: "72%", rotateX: 82, opacity: 0, filter: "blur(3px)" }}
          transition={reduceMotion ? { duration: 0.12 } : { type: "spring", stiffness: 520, damping: 34, mass: 0.68 }}
          className="absolute inset-0 grid place-items-center font-mono text-[19px] font-semibold tabular-nums text-white sm:text-[22px]"
          style={{ transformOrigin: "50% 50%" }}
        >
          {value}
        </motion.span>
      </AnimatePresence>
    </span>
  );
}

const HOUR_MS = 3_600_000;
const WEEK_MS = 7 * 24 * HOUR_MS;

/** Views on every post Vello's agents published in the last 7 days. The
 *  window start is rounded down to the hour (and re-rolled hourly) so the
 *  Convex subscription args stay stable between ticks. */
function LiveViewsCounter() {
  const [since, setSince] = useState(() => Math.floor((Date.now() - WEEK_MS) / HOUR_MS) * HOUR_MS);
  useEffect(() => {
    const id = setInterval(() => setSince(Math.floor((Date.now() - WEEK_MS) / HOUR_MS) * HOUR_MS), 60_000);
    return () => clearInterval(id);
  }, []);
  const week = useQuery(api.platformStats.weekViews, { since });
  const weekViews = Math.max(0, Math.floor(week?.views ?? 0));
  const characters = weekViews.toLocaleString("en-US").split("");

  return (
    <div className="mb-4 flex flex-col items-center" aria-live="polite" aria-label={`${weekViews.toLocaleString()} views this week`}>
      <div className="mb-2 flex items-center gap-1.5 text-[10px] font-semibold uppercase tracking-[0.16em] text-white/45">
        <span className="relative flex size-1.5" aria-hidden>
          <span className="absolute inset-0 animate-ping rounded-full bg-emerald-400 opacity-55" />
          <span className="relative size-1.5 rounded-full bg-emerald-400 shadow-[0_0_8px_rgba(52,211,153,0.9)]" />
        </span>
        Views this week
      </div>
      <motion.div
        layout
        className="flex min-h-9 items-center justify-center gap-1"
        transition={{ layout: { type: "spring", stiffness: 430, damping: 38 } }}
      >
        {characters.map((character, index) => (
          <FlipCharacter key={`${characters.length}-${index}`} value={character} index={index} />
        ))}
      </motion.div>
    </div>
  );
}


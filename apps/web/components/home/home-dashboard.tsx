function fmtDate(ts: number) {
  const s = Math.max(0, Math.floor((Date.now() - ts) / 1000));
  if (s < 60) return "just now";
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}min${m === 1 ? "" : "s"} ago`;
  const h = Math.floor(m / 60);
  if (h < 24) return `${h}hr${h === 1 ? "" : "s"} ago`;
  const d = Math.floor(h / 24);
  if (d < 7) return `${d}d ago`;
  return new Date(ts).toLocaleDateString(undefined, { month: "short", day: "numeric" });
}

function fmtTime(s: number): string {
  const m = Math.floor(s / 60);
  const sec = Math.floor(s % 60);
  return `${m.toString().padStart(2, "0")}:${sec.toString().padStart(2, "0")}`;
}

function ProjectCard({ item, onOpen }: { item: FeedItem; onOpen: (item: FeedItem) => void }) {
  const [duration, setDuration] = useState<number | null>(null);
  const videoRef = useRef<HTMLVideoElement>(null);
  // Muted preview plays on hover, rewinds to the first frame on leave.
  const hoverPlay = () => { videoRef.current?.play().catch(() => {}); };
  const hoverStop = () => {
    const v = videoRef.current;
    if (!v) return;
    v.pause();
    v.currentTime = 0.001;
  };

  const [downloading, setDownloading] = useState(false);
  // Cross-origin video URLs (R2/CDN) ignore the `download` attribute on a bare
  // <a> — the browser just navigates/opens a new tab instead of saving. Pull
  // the bytes into a blob first so the save is instant and actually a download.
  const download = async (e: React.MouseEvent) => {
    e.stopPropagation();
    if (downloading) return;
    setDownloading(true);
    try {
      const res = await fetch(item.videoUrl);
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${item.caption || item.agentName || "clip"}.mp4`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
    } catch {
      // CORS/network hiccup — fall back to opening the video directly so the
      // user can still save it manually rather than nothing happening.
      window.open(item.videoUrl, "_blank", "noopener,noreferrer");
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="group flex flex-col">
      <button
        type="button"
        onClick={() => onOpen(item)}
        onMouseEnter={hoverPlay}
        onMouseLeave={hoverStop}
        onFocus={hoverPlay}
        onBlur={hoverStop}
        className="relative block aspect-[9/16] w-full overflow-hidden rounded-xl bg-neutral-900"
      >
        {/* First frame of the actual video, not the generated poster image.
            The #t=0.001 media fragment forces browsers to seek+paint frame 0
            with preload="metadata" (Safari otherwise leaves the tile blank).
            Same element doubles as the duration probe. */}
        <video
          ref={videoRef}
          src={`${item.videoUrl}#t=0.001`}
          muted
          loop
          playsInline
          preload="metadata"
          onLoadedMetadata={(e) => setDuration(e.currentTarget.duration)}
          className="absolute inset-0 size-full object-cover opacity-95 transition-transform duration-300 group-hover:scale-105"
        />
        <div aria-hidden className="pointer-events-none absolute inset-0 bg-gradient-to-t from-black/50 via-transparent to-transparent" />
        {duration != null && (
          <span className="absolute right-2 top-2 flex items-center gap-1.5 rounded-full bg-black/60 px-2.5 py-1 text-[11px] font-semibold tabular-nums text-white/90 backdrop-blur-sm">
            00:00 <span className="text-white/50">{fmtTime(duration)}</span>
          </span>
        )}
      </button>

      {/* Action row — calendar (opens this project's Schedule tab), download
          (instant, no new tab), editor (opens this project's Editor tab) */}
      <div className="mt-3 flex items-center justify-center gap-6 text-white/60">
        <Link
          href={`/builder?mint=${item.mint}&tab=schedule`}
          onClick={(e) => e.stopPropagation()}
          title={`Posted ${fmtDate(item.createdAt)} — open Schedule`}
          className="transition-colors hover:text-white"
        >
          <Calendar className="size-[18px]" />
        </Link>
        <button type="button" onClick={download} disabled={downloading} title="Download" className="transition-colors hover:text-white disabled:opacity-50">
          {downloading ? <Loader2 className="size-[18px] animate-spin" /> : <Download className="size-[18px]" />}
        </button>
        <Link
          href={`/builder?mint=${item.mint}&tab=editor`}
          onClick={(e) => e.stopPropagation()}
          title="Open in Editor"
          className="transition-colors hover:text-white"
        >
          <Scissors className="size-[18px]" />
        </Link>
      </div>

      <p className="mt-3 line-clamp-2 text-[15px] font-medium leading-snug text-white" title={item.caption || item.agentName}>
        {item.caption || `${item.agentName} — clip`}
      </p>
      <div className="mt-1.5 flex items-center gap-2">
        <span className="text-[12px] tabular-nums text-white/40">{fmtDate(item.createdAt)}</span>
        {item.state === "posted" && (
          <ConnectedPlatformStack platforms={item.postedPlatforms} badgeClassName="size-4" ringClassName="ring-neutral-950" />
        )}
      </div>
    </div>
  );
}

/* ─────────────────────────────────────────────────────────
 * ANIMATION STORYBOARD — Recent-clip player modal
 *
 *    0ms   backdrop fades in (dim + blur)
 *    0ms   player panel springs 0.94 → 1.0, rises 16px
 *   90ms   title bar (avatar + caption + close) fades down
 *  140ms   control bar fades up
 *
 * Exit: panel scales back down + backdrop fades, together.
 * ───────────────────────────────────────────────────────── */
const MODAL_TIMING = {
  backdrop: { fadeIn: 0.25, fadeOut: 0.18 },
  panel: { type: "spring" as const, stiffness: 320, damping: 30 },
  panelScale: 0.94,
  panelRise: 16,
  titleDelay: 0.09,
  controlsDelay: 0.14,
  chrome: { type: "spring" as const, stiffness: 380, damping: 32 },
};

function fmtClock(s: number): string {
  if (!Number.isFinite(s) || s < 0) return "0:00";
  const m = Math.floor(s / 60);
  return `${m}:${String(Math.floor(s % 60)).padStart(2, "0")}`;
}

// ── Video modal — animated fullscreen player (custom controls, no cropping) ──
function VideoModal({ item, onClose }: { item: FeedItem; onClose: () => void }) {
  const reduce = useReducedMotion();
  const shellRef = useRef<HTMLDivElement>(null);
  const videoRef = useRef<HTMLVideoElement>(null);
  const [playing, setPlaying] = useState(true);
  const [muted, setMuted] = useState(false);
  const [time, setTime] = useState(0);
  const [duration, setDuration] = useState(0);

  const togglePlay = useCallback(() => {
    const v = videoRef.current;
    if (!v) return;
    if (v.paused) { void v.play(); setPlaying(true); }
    else { v.pause(); setPlaying(false); }
  }, []);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
      if (e.key === " ") { e.preventDefault(); togglePlay(); }
      if (e.key === "m") setMuted((v) => !v);
    };
    document.addEventListener("keydown", onKey);
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.removeEventListener("keydown", onKey);
      document.body.style.overflow = prev;
    };
  }, [onClose, togglePlay]);


  const seek = (pct: number) => {
    const v = videoRef.current;
    if (!v || !Number.isFinite(v.duration)) return;
    v.currentTime = (pct / 100) * v.duration;
  };

  const goFullscreen = () => {
    const el = shellRef.current;
    if (!el) return;
    if (document.fullscreenElement) void document.exitFullscreen();
    else void el.requestFullscreen?.();
  };

  const progressPct = duration > 0 ? (time / duration) * 100 : 0;

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 sm:p-6">
      {/* Layer 1: backdrop */}
      <motion.div
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        exit={{ opacity: 0, transition: { duration: MODAL_TIMING.backdrop.fadeOut } }}
        transition={{ duration: MODAL_TIMING.backdrop.fadeIn }}
        className="absolute inset-0 bg-black/85 backdrop-blur-md"
        onClick={onClose}
      />

      {/* Layer 2: player panel */}
      <motion.div
        ref={shellRef}
        initial={reduce ? { opacity: 0 } : { opacity: 0, scale: MODAL_TIMING.panelScale, y: MODAL_TIMING.panelRise }}
        animate={{ opacity: 1, scale: 1, y: 0 }}
        exit={reduce ? { opacity: 0 } : { opacity: 0, scale: MODAL_TIMING.panelScale, y: MODAL_TIMING.panelRise, transition: { duration: 0.18 } }}
        transition={MODAL_TIMING.panel}
        className="relative z-10 flex max-h-[92vh] flex-col overflow-hidden rounded-2xl bg-black ring-1 ring-white/15 shadow-[0_40px_120px_-24px_rgba(0,0,0,0.95)]"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Layer 3a: title bar */}
        <motion.div
          initial={reduce ? false : { opacity: 0, y: -8 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ ...MODAL_TIMING.chrome, delay: MODAL_TIMING.titleDelay }}
          className="pointer-events-none absolute inset-x-0 top-0 z-20 flex items-center gap-2.5 bg-gradient-to-b from-black/80 to-transparent px-3.5 pb-8 pt-3"
        >
          <AgentAvatar url={item.agentAvatar} name={item.agentName} seed={item.agentName} alt="" className="size-7 shrink-0 rounded-full object-cover ring-1 ring-white/20" initialClassName="text-[11px]" />
          <div className="min-w-0 flex-1">
            <p className="truncate text-[13px] font-semibold text-white">{item.agentName}</p>
            {item.caption && <p className="truncate text-[11px] text-white/60">{item.caption}</p>}
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="pointer-events-auto flex size-8 shrink-0 items-center justify-center rounded-full bg-white/10 text-white transition-colors hover:bg-white/25"
          >
            <X className="size-4" />
          </button>
        </motion.div>

        {/* Video — click toggles play */}
        <video
          ref={videoRef}
          src={item.videoUrl}
          poster={item.posterUrl ?? undefined}
          autoPlay
          playsInline
          muted={muted}
          onClick={togglePlay}
          onTimeUpdate={(e) => setTime(e.currentTarget.currentTime)}
          onLoadedMetadata={(e) => setDuration(e.currentTarget.duration)}
          onEnded={() => setPlaying(false)}
          className="max-h-[92vh] max-w-[92vw] cursor-pointer bg-black object-contain"
        />

        {/* Center play glyph when paused */}
        <AnimatePresence>
          {!playing && (
            <motion.button
              type="button"
              onClick={togglePlay}
              aria-label="Play"
              initial={{ opacity: 0, scale: 0.8 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.8 }}
              transition={MODAL_TIMING.chrome}
              className="absolute inset-0 z-10 m-auto flex size-16 items-center justify-center rounded-full bg-black/55 text-white ring-1 ring-white/25 backdrop-blur-sm"
            >
              <Play className="size-6 translate-x-0.5 fill-current" />
            </motion.button>
          )}
        </AnimatePresence>

        {/* Layer 3b: control bar */}
        <motion.div
          initial={reduce ? false : { opacity: 0, y: 8 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ ...MODAL_TIMING.chrome, delay: MODAL_TIMING.controlsDelay }}
          className="absolute inset-x-0 bottom-0 z-20 bg-gradient-to-t from-black/85 to-transparent px-3.5 pb-3 pt-10"
        >
          {/* Scrubber */}
          <input
            type="range"
            min={0}
            max={100}
            step={0.1}
            value={progressPct}
            onChange={(e) => seek(Number(e.target.value))}
            aria-label="Seek"
            className="h-1 w-full cursor-pointer appearance-none rounded-full accent-white"
            style={{ background: `linear-gradient(to right, #fff ${progressPct}%, rgba(255,255,255,0.25) ${progressPct}%)` }}
          />
          <div className="mt-2 flex items-center gap-3 text-white">
            <button type="button" onClick={togglePlay} aria-label={playing ? "Pause" : "Play"} className="transition-transform active:scale-90">
              {playing ? <Pause className="size-[18px] fill-current" /> : <Play className="size-[18px] fill-current" />}
            </button>
            <button type="button" onClick={() => setMuted((v) => !v)} aria-label={muted ? "Unmute" : "Mute"} className="transition-transform active:scale-90">
              {muted ? <VolumeX className="size-[18px]" /> : <Volume2 className="size-[18px]" />}
            </button>
            <span className="text-[11.5px] tabular-nums text-white/80">{fmtClock(time)} / {fmtClock(duration)}</span>
            <div className="flex-1" />
            <a
              href={item.videoUrl}
              download
              target="_blank"
              rel="noreferrer"
              aria-label="Download"
              className="text-white/80 transition-colors hover:text-white"
              onClick={(e) => e.stopPropagation()}
            >
              <Download className="size-[18px]" />
            </a>
            <button type="button" onClick={goFullscreen} aria-label="Fullscreen" className="transition-transform active:scale-90">
              <Maximize className="size-[18px]" />
            </button>
          </div>
        </motion.div>

        {/* Taste feedback — under the video, outside the overlay chrome. */}
        <div className="flex flex-col items-center gap-1.5 bg-black px-3.5 py-2.5">
          {item.formatId && (
            <p className="max-w-full truncate text-[11px] text-white/45">
              {formatById(item.formatId)?.name ?? item.formatId}
              {item.caption ? ` · ${item.caption.slice(0, 60)}` : ""}
            </p>
          )}
          <VideoFeedback mintAddress={item.mint} videoTitle={item.caption} formatId={item.formatId ?? undefined} />
        </div>
      </motion.div>
    </div>
  );
}


"use client";

import { useState } from "react";
import Link from "next/link";
import Image from "next/image";
import { motion, AnimatePresence } from "framer-motion";
import { FileStack, Clock, Megaphone, Trophy, Bot, Trash2, Loader2 } from "lucide-react";
import type { Campaign } from "@/lib/types";
import { ConnectedPlatformStack } from "@/components/social/platform-icons";

const NOW = Date.now();

function seedIndex(str: string) {
  let h = 0;
  for (let i = 0; i < str.length; i++) h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  return Math.abs(h);
}

// loremflickr — real cyberpunk/neon photos, deterministic by lock number
function cyberpunkCover(seed: string) {
  const lock = (seedIndex(seed) % 50) + 1;
  return `https://loremflickr.com/640/360/cyberpunk,neon,futuristic?lock=${lock}`;
}

// robohash — unique robot/cyborg avatar per brand name, NFT-style
function robotAvatar(seed: string) {
  return `https://robohash.org/${encodeURIComponent(seed)}?set=set1&size=100x100&bgset=bg2`;
}

function isAutoGenerated(url?: string | null) {
  return !url || url.includes("dicebear.com") || url.trim() === "";
}

// Keyed by `string`, not `Campaign["status"]`, because the admin campaigns editor
// can write statuses outside the strict union (active / pending / expired) — an
// unmapped value must never crash the /stage list (it did: `undefined.class`).
const STATUS_META: Record<string, { label: string; class: string }> = {
  open:        { label: "Open",        class: "bg-emerald-500/20 text-emerald-300 border-emerald-400/30" },
  active:      { label: "Active",      class: "bg-emerald-500/20 text-emerald-300 border-emerald-400/30" },
  in_progress: { label: "In Progress", class: "bg-blue-500/20 text-blue-300 border-blue-400/30" },
  pending:     { label: "Pending",     class: "bg-amber-500/20 text-amber-300 border-amber-400/30" },
  completed:   { label: "Completed",   class: "bg-zinc-500/20 text-zinc-300 border-zinc-400/30" },
  expired:     { label: "Expired",     class: "bg-zinc-500/20 text-zinc-400 border-zinc-400/30" },
  cancelled:   { label: "Cancelled",   class: "bg-red-500/20 text-red-300 border-red-400/30" },
};

/** Safe status badge — never throws on an unknown status value. */
const FALLBACK_STATUS = { label: "—", class: "bg-zinc-500/20 text-zinc-300 border-zinc-400/30" };

const TYPE_META: Record<string, { icon: React.ElementType; label: string; class: string }> = {
  marketing:  { icon: Megaphone, label: "Marketing",  class: "bg-blue-500/15 text-blue-300 border-blue-500/25" },
  bounty:     { icon: Trophy,    label: "Bounty",     class: "bg-amber-500/15 text-amber-300 border-amber-500/25" },
  agent_task: { icon: Bot,       label: "Agent Task", class: "bg-violet-500/15 text-violet-300 border-violet-500/25" },
};

interface CampaignCardProps {
  campaign: Campaign;
  /** Restricted-to-owner campaign, viewed by a NON-allowed user: show a small
   *  "🔒 Exclusive" badge. Purely cosmetic — the real gates are server-side. */
  locked?: boolean;
  /** Whether the viewing wallet created this campaign. Only the owner sees the
   *  delete control (the /api/campaigns/delete route is ownership-gated too, so
   *  this is a UI affordance, not the security boundary). Defaults to false. */
  isOwner?: boolean;
}

export function CampaignCard({ campaign, locked = false, isOwner = false }: CampaignCardProps) {
  const [coverBroken, setCoverBroken] = useState(false);
  const [logoBroken, setLogoBroken] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [hovered, setHovered] = useState(false);

  // Campaign requirements revealed in the hover panel (like the exclusive cards).
  // Prefer the structured `requirements`; fall back to splitting free-text
  // `deliverables`. Drop URLs/empties so the list stays clean.
  const requirements = (
    campaign.requirements && campaign.requirements.length
      ? campaign.requirements
      : (campaign.deliverables ? campaign.deliverables.split(/\n|·|;|•/) : [])
  )
    .map((r) => r.trim())
    .filter((r) => r && !r.startsWith("http") && r.length > 2)
    .slice(0, 6);

  /**
   * Retire a FUNDED campaign. Deleting one would cascade-delete its submissions and
   * strand the on-chain vault — the row is what the reclaim flow reads — so a funded
   * campaign is archived instead: off every board, money still reclaimable.
   */
  async function handleArchive(e: React.MouseEvent) {
    e.preventDefault();
    e.stopPropagation();
    if (deleting) return;
    if (!window.confirm(`Archive "${campaign.title}"? It disappears from the boards and pickers. Its submissions stay, and you can still reclaim any escrow from your wallet.`)) return;
    setDeleting(true);
    try {
      const res = await fetch("/api/campaigns/archive", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ campaignId: campaign.id }),
      });
      if (!res.ok) throw new Error(`archive failed (${res.status})`);
      // Reactive query — the card drops out on its own.
    } catch {
      setDeleting(false);
      window.alert("Couldn't archive the campaign. You can only archive your own campaigns.");
    }
  }

  async function handleDelete(e: React.MouseEvent) {
    e.preventDefault();   // don't follow the card's <Link>
    e.stopPropagation();
    if (deleting) return;
    if (!window.confirm(`Delete campaign "${campaign.title}"? This removes it and its submissions.`)) return;
    setDeleting(true);
    try {
      // Goes through the SIWS-gated route (the convex mutation is secret-gated +
      // ownership-checked there). The global fetch interceptor attaches auth.
      const res = await fetch("/api/campaigns/delete", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ campaignId: campaign.id }),
      });
      if (!res.ok) throw new Error(`delete failed (${res.status})`);
      // The list query is reactive — the card disappears on its own.
    } catch {
      setDeleting(false);
      window.alert("Couldn't delete the campaign. You can only delete your own campaigns.");
    }
  }

  const seed = campaign.title + campaign.brandName;
  const coverSrc = campaign.campaignImageUrl && !coverBroken ? campaign.campaignImageUrl : cyberpunkCover(seed);
  const logoSrc = !isAutoGenerated(campaign.brandLogoUrl) && !logoBroken ? campaign.brandLogoUrl! : robotAvatar(campaign.brandName);

  const daysLeft = Math.ceil((new Date(campaign.deadline).getTime() - NOW) / 86400000);
  const typeMeta = campaign.campaignType ? TYPE_META[campaign.campaignType] : null;
  const TypeIcon = typeMeta?.icon;
  // Show the stacked platform logos whenever the campaign specifies platforms;
  // otherwise fall back to the campaign-type badge. (ConnectedPlatformStack also
  // no-ops on platforms it can't render, so this stays safe for unknown ids.)
  const hasPlatforms = !!campaign.platforms && campaign.platforms.length > 0;
  // Ended = deadline passed OR explicitly closed out — shown in red instead of
  // whatever its raw status badge would otherwise be.
  const isEnded = daysLeft <= 0 || campaign.status === "completed" || campaign.status === "cancelled";
  const statusMeta = STATUS_META[campaign.status] ?? FALLBACK_STATUS;

  // Budget-used bar — estimate from completed submissions × per-completion reward.
  const estPaid = campaign.rewardPerCompletion
    ? Math.min(campaign.budget, campaign.submissionsCount * campaign.rewardPerCompletion)
    : 0;
  const pct = campaign.budget > 0 ? Math.max(0, Math.min(100, (estPaid / campaign.budget) * 100)) : 0;

  const rateLabel = campaign.campaignType === "marketing"
    ? `$${campaign.ratePerThousandViews}/1K`
    : campaign.rewardPerCompletion
    ? `$${campaign.rewardPerCompletion}/task`
    : "Pool";

  return (
    // self-start keeps the grid cell at its natural height; the absolute requirements
    // panel below is anchored to the motion wrapper so the grid never reflows on hover.
    <div className="self-start" onMouseEnter={() => setHovered(true)} onMouseLeave={() => setHovered(false)}>
      <motion.div
        whileHover={{ y: -14, scale: 1.035, transition: { type: "spring", stiffness: 340, damping: 24, mass: 0.75 } }}
        style={{ zIndex: hovered ? 50 : 1, position: "relative" }}
      >
      <Link href={`/stage/${campaign.id}`} className="block cursor-pointer">
        <div className={`overflow-hidden border bg-[#161618] transition-[border-color,box-shadow] duration-300 ${
          hovered && requirements.length > 0
            ? isEnded
              ? "rounded-t-md border-x-red-400/45 border-t-red-400/45 border-b-transparent"
              : "rounded-t-md border-x-lime-300/45 border-t-lime-300/45 border-b-transparent"
            : "rounded-md"
        } ${
          isEnded
            ? "border-red-500/25"
            : hovered
            ? "shadow-[0_28px_70px_rgba(132,204,22,0.22)]"
            : "border-[#2e2e33]"
        }`}>

        {/* 16:9 cover */}
        <div className="relative aspect-[16/9] w-full overflow-hidden bg-[#18181b]">
          <img
            src={coverSrc}
            alt={campaign.title}
            loading="lazy"
            decoding="async"
            className={`h-full w-full object-cover object-center transition-transform duration-700 ${hovered ? "scale-105" : "scale-100"}`}
            onError={() => setCoverBroken(true)}
          />
          <div className="absolute inset-x-0 bottom-0 h-[50%] bg-[linear-gradient(180deg,transparent_0%,rgba(0,0,0,0.28)_50%,rgba(0,0,0,0.76)_100%)]" />

          {isEnded ? (
            <>
              <div className="absolute inset-0 bg-[linear-gradient(160deg,rgba(239,68,68,0.32)_0%,rgba(30,4,4,0.55)_55%,rgba(10,2,2,0.8)_100%)]" />
              <div className="absolute inset-0 flex items-center justify-center">
                <span className="text-[13px] font-bold uppercase tracking-[0.18em] text-red-50 [text-shadow:0_2px_16px_rgba(0,0,0,0.85)]">
                  Campaign Ended
                </span>
              </div>
            </>
          ) : (
            <span className={`absolute top-2.5 left-2.5 rounded-full border px-2 py-0.5 text-[10px] font-semibold backdrop-blur-sm ${statusMeta.class}`}>
              {statusMeta.label}
            </span>
          )}

          {/* Delete — owner-only. Hidden entirely for campaigns the viewer doesn't
              own (the delete route is ownership-gated server-side regardless). */}
          {isOwner && (
            <button
              type="button"
              // A funded campaign is ARCHIVED, never deleted: deleting it would take
              // its submissions with it and orphan the escrow vault.
              onClick={campaign.pdaAddress ? handleArchive : handleDelete}
              disabled={deleting}
              aria-label={campaign.pdaAddress ? "Archive campaign" : "Delete campaign"}
              title={campaign.pdaAddress ? "Archive — hides it everywhere; escrow stays reclaimable" : "Delete campaign"}
              className="absolute top-2.5 right-2.5 z-10 inline-flex size-7 items-center justify-center rounded-full border border-white/15 bg-black/55 text-white/80 backdrop-blur-md transition-colors hover:border-red-400/50 hover:bg-red-500/25 hover:text-red-200 disabled:opacity-60"
            >
              {deleting ? <Loader2 className="size-3.5 animate-spin" /> : <Trash2 className="size-3.5" strokeWidth={2.2} />}
            </button>
          )}

          {locked && (
            <span className="absolute bottom-2.5 left-2.5 z-10 inline-flex items-center gap-1 rounded-full border border-amber-400/30 bg-black/60 px-2 py-0.5 text-[10px] font-semibold text-amber-200 backdrop-blur-md">
              🔒 Exclusive
            </span>
          )}

          <span className="absolute bottom-2.5 right-2.5 inline-flex items-center gap-1 rounded-full border border-white/12 bg-black/55 px-2 py-0.5 text-[10px] font-bold backdrop-blur-md">
            <Clock className="size-2.5 text-white/70" strokeWidth={2.4} />
            <span className={daysLeft <= 0 ? "text-zinc-300" : daysLeft <= 7 ? "text-red-300" : "text-white"}>
              {daysLeft > 0 ? `${daysLeft}d left` : "Ended"}
            </span>
          </span>
        </div>

        {/* Body */}
        <div className="flex flex-col px-4 pt-3">
          {/* Author row */}
          <div className="flex min-w-0 items-center gap-1.5 mb-1.5">
            <img
              src={logoSrc}
              alt={campaign.brandName}
              className="h-[18px] w-[18px] shrink-0 rounded-full object-cover ring-1 ring-white/20"
              onError={() => setLogoBroken(true)}
            />
            <span
              className="min-w-0 truncate text-[12.5px] font-medium leading-none tracking-[-0.01em] text-white/90"
              style={{ fontFamily: '-apple-system, "SF Pro Text", BlinkMacSystemFont, var(--font-inter, Inter), system-ui, sans-serif' }}
            >
              {campaign.brandName}
            </span>
            <Image src="/green-gem-reward.svg" alt="" width={13} height={13} className="shrink-0 [filter:drop-shadow(0_0_5px_rgba(52,211,153,0.5))]" unoptimized />
            {/* Stacked social-platform logos this campaign accepts posts on —
                dynamic from campaign.platforms, overlapping like the exclusive stack.
                Falls back to the campaign-type badge when no platforms are set. */}
            {hasPlatforms ? (
              <ConnectedPlatformStack
                platforms={campaign.platforms}
                max={4}
                badgeClassName="size-[18px]"
                ringClassName="ring-[#161618]"
                className="ml-auto"
              />
            ) : typeMeta ? (
              <span className={`ml-auto inline-flex items-center gap-1 rounded-full border px-1.5 py-0.5 text-[9.5px] font-semibold ${typeMeta.class}`}>
                {TypeIcon && <TypeIcon className="size-2.5" />}
                {typeMeta.label}
              </span>
            ) : null}
          </div>

          {/* Title */}
          <h3 className="min-w-0 text-[14.5px] font-bold leading-snug tracking-[-0.01em] text-white truncate">
            {campaign.title}
          </h3>

          {/* Description */}
          <p className="mt-1 text-[11.5px] leading-[1.5] text-white/55 line-clamp-2">
            {campaign.brief}
          </p>

          {/* Budget + stats */}
          <div className="mt-3 flex items-end justify-between">
            <div className="flex items-baseline gap-1">
              <span className="text-[13px] font-bold text-white">${estPaid.toLocaleString()}</span>
              <span className="text-[13px] font-bold text-[#9ca3af]">/ ${campaign.budget.toLocaleString()}</span>
            </div>
            <div className="flex shrink-0 items-center -space-x-2">
              <div className="relative z-[2] flex h-[24px] items-center gap-1 rounded-full border border-white/12 bg-[linear-gradient(145deg,rgba(255,255,255,0.15),rgba(255,255,255,0.04))] px-2 shadow-[inset_0_1px_0_rgba(255,255,255,0.2)] backdrop-blur-md">
                <FileStack className="h-2.5 w-2.5 shrink-0 text-white/70" strokeWidth={2.2} />
                <span className="text-[10px] font-bold tabular-nums leading-none text-white">
                  {campaign.submissionsCount.toLocaleString()}
                </span>
              </div>
              <div className="relative z-[1] flex h-[24px] items-center rounded-full border border-[#93c5fd]/30 bg-[linear-gradient(145deg,rgba(59,130,246,0.28),rgba(30,64,175,0.12))] px-2 shadow-[inset_0_1px_0_rgba(191,219,254,0.3)] backdrop-blur-md">
                <span className="text-[10px] font-bold leading-none text-[#bfdbfe]">{rateLabel}</span>
              </div>
            </div>
          </div>

          {/* Progress bar — in the card only when there's no requirements panel;
              otherwise it moves to the bottom of the expanded panel (like exclusive). */}
          {requirements.length === 0 && (
            <div className="relative mt-3 -mx-4 h-[6px] bg-[#0c1a0d]">
              <div
                className={`h-full rounded-r-full transition-all duration-700 ${
                  isEnded
                    ? "bg-[linear-gradient(90deg,#f87171_0%,#ef4444_55%,#dc2626_100%)] shadow-[0_0_10px_rgba(239,68,68,0.9),0_0_24px_rgba(248,113,113,0.5)]"
                    : "bg-[linear-gradient(90deg,#34d399_0%,#22c55e_55%,#4ade80_100%)] shadow-[0_0_10px_rgba(34,197,94,0.9),0_0_24px_rgba(74,222,128,0.5)]"
                }`}
                style={{ width: `${Math.max(5, pct)}%` }}
              />
            </div>
          )}
        </div>
        </div>

        {/* Requirements panel — reveals on hover and is appended flush under the card
            (absolute top-full so the grid never reflows), exactly like the exclusive cards. */}
        <AnimatePresence>
          {hovered && requirements.length > 0 && (
            <motion.div
              key="req-panel"
              initial={{ height: 0, opacity: 0 }}
              animate={{ height: "auto", opacity: 1 }}
              exit={{ height: 0, opacity: 0 }}
              transition={{ duration: 0.26, ease: [0.22, 1, 0.36, 1] }}
              className={`absolute left-0 right-0 top-full z-10 overflow-hidden rounded-b-md border border-t-0 bg-[#161618] px-4 shadow-[0_28px_40px_rgba(0,0,0,0.55)] ${isEnded ? "border-red-400/45" : "border-lime-300/45"}`}
            >
              <p className={`pt-2 text-[9.5px] font-bold uppercase tracking-wide ${isEnded ? "text-red-300/70" : "text-lime-300/70"}`}>Requirements</p>
              <ul className="pb-5 pt-1 space-y-1.5">
                {requirements.slice(0, 4).map((req, i) => (
                  <motion.li
                    key={i}
                    initial={{ opacity: 0, x: -5 }}
                    animate={{ opacity: 1, x: 0 }}
                    transition={{ delay: 0.05 + i * 0.04, duration: 0.18 }}
                    className="flex items-start gap-2 text-[11px] leading-[1.5] text-white/60"
                  >
                    <span className="mt-[4px] h-[5px] w-[5px] shrink-0 rounded-full bg-emerald-500/60" />
                    {req}
                  </motion.li>
                ))}
              </ul>
              <div className="pointer-events-none absolute inset-x-0 bottom-0 h-[6px] bg-[#0c1a0d]">
                <div
                  className={`h-full rounded-r-full transition-all duration-700 ${
                    isEnded
                      ? "bg-[linear-gradient(90deg,#f87171_0%,#ef4444_55%,#dc2626_100%)] shadow-[0_0_10px_rgba(239,68,68,0.9),0_0_24px_rgba(248,113,113,0.5)]"
                      : "bg-[linear-gradient(90deg,#34d399_0%,#22c55e_55%,#4ade80_100%)] shadow-[0_0_10px_rgba(34,197,94,0.9),0_0_24px_rgba(74,222,128,0.5)]"
                  }`}
                  style={{ width: `${Math.max(5, pct)}%` }}
                />
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </Link>
      </motion.div>
    </div>
  );
}
